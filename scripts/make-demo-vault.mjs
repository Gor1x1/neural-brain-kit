let notes = 0, links = 0;
const walk = (d) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const f = path.join(d, e.name);
    if (e.isDirectory()) walk(f);
    else if (e.name.endsWith('.md')) { notes++; links += (fs.readFileSync(f, 'utf8').match(/\[\[[^\]]+\]\]/g) || []).length; }
  }
};
walk(OUT);

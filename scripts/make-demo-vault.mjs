const fm = (p) => `---\ntype: ${p.type}\ncreated: ${p.created}\nupdated: ${p.updated}\ntags: [${p.tags.join(', ')}]\nstatus: ${p.status}\n---\n`;
const bullets = (ids) => ids.map((x) => `- ${wl(x)}`).join('\n');
const sec = (h, body) => `## ${h}\n\n${body}\n`;
const seeAlso = (p, extra = []) => {
  const o = L(p.id);
  const ids = [...o.see];
  const unr = UNRESOLVED[p.id];
  const lines = ids.map((x) => `- ${wl(x)}`);
  if (unr) lines.push(`- ${wl(unr)} (unverified)`);
  for (const x of extra) lines.push(x);
  return lines.length ? sec('Related', lines.join('\n')) : '';
};
const subset = (arr) => arr.filter(() => chance(0.55));

function render(p) {
  const head = fm(p) + `\n# ${p.title}\n\n`;
  const o = L(p.id);
  switch (p.type) {
    case 'concept': {
      const parts = [sec('Definition', DEF[p.id])];
      if (chance(0.7)) parts.push(sec('Why it matters', pick(WHY)));
      if (chance(0.55)) parts.push(sec('Example', pick(EXAMPLE)));
      parts.push(seeAlso(p));
      return head + parts.join('\n');
    }
    case 'source': {
      const sid = p.id;
      const inl = [...o.inline].map(wl).join(', ');
      return head + [
        sec('Summary', DEF[stripDate(sid)]),
        sec('Key ideas', `The key ideas concern these concepts: ${inl}.`),
        seeAlso(p),
      ].join('\n');
    }
    case 'entity':
      return head + [sec('Description', DEF[p.id]), sec('Where it is used', pick(USE)), seeAlso(p)].join('\n');
    case 'project': {
      const st = p.status === 'draft' ? 'Planned.' : 'In progress.';
      return head + [sec('Goal', DEF[p.id]), sec('Steps', pick(STEPS)), sec('Status', st), seeAlso(p)].join('\n');
    }
    case 'raw': {
      const sid = p.id.slice(4);
      return head + [
        sec('Notes on the original', DEF[stripDate(sid)]),
        sec('Metadata', `- Type: article\n- Date: ${p.created}`),
      ].join('\n');
    }
    case 'journal': {
      const row = JOURNAL.find((r) => r[0] === p.id);
      return head + [
        sec('Today', row[1]),
        sec('Thoughts for tomorrow', pick(TOMORROW)),
        sec('Links', bullets([...o.see])),
      ].join('\n');
    }
    case 'study': {
      const row = STUDY.find((r) => r[0] === p.id);
      return head + [
        sec('Description', row[2]),
        sec('Exercise', 'Do three small exercises and check the answers.'),
        sec('Related', bullets([...o.see])),
      ].join('\n');
    }
    case 'inbox': {
      const row = INBOX.find((r) => r[0] === p.id);
      return head + [sec('Thought', row[1]), sec('Links', bullets([...o.see]))].join('\n');
    }
  }
  throw new Error('unknown type ' + p.type);
}

const write = (rel, text) => {
  const f = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, text.endsWith('\n') ? text : text + '\n');
};
for (const p of pages) write(p.rel, render(p));

